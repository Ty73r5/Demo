/* Quotation register. Run: node tools/quote_register.js [--write]
   Finds every quotation (“…”) in the atlas content and sorts it into:
   - Scripture or Qur'an wording followed by its reference: checked automatically against the generated text of that
     passage (any translation in the reader). A mismatch fails the run.
   - Everything else: hand-entered quotations of creeds, Fathers, rabbis, philosophers and modern writers. These cannot
     be checked by script; the register records where each sits and whether a locator (a reference or link) follows it.
   With --write, saves docs/QUOTATIONS.md. Matching wording to a passage does not show that the passage means what the
   prose says; a locator does not show that the quotation is accurate. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const dir = path.join(__dirname, '..', 'assets', 'data');
const ctx = { console }; ctx.window = ctx; vm.createContext(ctx);
for (const f of require('./data_files.json')) vm.runInContext(fs.readFileSync(path.join(dir, f), 'utf8'), ctx, { filename: f });
const { BIBLE, QURAN } = ctx;

const norm = s => String(s).toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[’'`]/g, '').replace(/\[[^\]]*\]|\([^)]*\)/g, ' ').replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();
const skip = new Set(['BIBLE', 'QURAN', 'LEX', 'STATS', 'GEO', 'L', 'SOURCES', 'SOURCE_ROLES', 'SOURCE_CHECKS', 'CORRECTIONS']);
const rows = [];
function scan(str, where) {
  // A quotation, then optionally the next 80 characters, which may hold its reference or locator.
  for (const m of str.matchAll(/“([^”]{12,})”([^“]{0,80})/g)) {
    const q = m[1], after = m[2];
    const ref = (after.match(/^\s*(?:\([^)]*\)\s*)?\{\{([^}]+)\}\}/) || [])[1];
    const locator = /^\s*[,.;:]?\s*(\(|\[|\{\{|\[\[)/.test(after) || /\d/.test(after.slice(0, 40));
    rows.push({ where, q, ref, locator });
  }
}
function walk(v, where) {
  if (typeof v === 'string') scan(v, where);
  else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${where}[${i}]`));
  else if (v && typeof v === 'object') {
    if (v.k === 'quote' && v.q) rows.push({ where, q: v.q.replace(/\{\{[^}]+\}\}/g, '').trim(), ref: null, locator: !!v.cite, cite: v.cite, block: true });
    for (const [k, x] of Object.entries(v)) if (!(v.k === 'quote' && k === 'q')) walk(x, `${where}.${k}`);
  }
}
for (const k of Object.keys(ctx)) if (/^[A-Z][A-Z_]+$/.test(k) && !skip.has(k)) walk(ctx[k], k);

let bad = 0;
for (const r of rows) {
  if (!r.ref) { r.kind = 'hand-entered'; continue; }
  const texts = r.ref.startsWith('Q:') ? (QURAN[r.ref.slice(2)] ? [QURAN[r.ref.slice(2)].en] : []) : (BIBLE[r.ref] ? Object.values(BIBLE[r.ref].tr) : []);
  // Quotations may elide words with “…”; each piece must appear in one translation.
  const pieces = r.q.split(/…|\.\.\./).map(norm).filter(p => p.length > 3);
  r.kind = r.ref.startsWith('Q:') ? 'Qur’an' : 'Scripture';
  r.match = texts.find(t => pieces.every(p => norm(t).includes(p)));
  if (!r.match) { bad++; r.status = 'NOT FOUND in the cited passage'; } else r.status = 'matches the generated text';
}
const scripture = rows.filter(r => r.kind !== 'hand-entered'), hand = rows.filter(r => r.kind === 'hand-entered');
const located = hand.filter(r => r.locator).length;
const summary = `${rows.length} quotations: ${scripture.length} Scripture or Qur’an quotations with a reference (${scripture.length - bad} match the generated text of the cited passage, ${bad} do not), and ${hand.length} hand-entered quotations (${located} followed by a reference or locator, ${hand.length - located} without one).`;
console.log(summary);
for (const r of scripture.filter(r => !r.match)) console.log(`NOT FOUND ${r.where}: “${r.q}” {{${r.ref}}}`);

if (process.argv.includes('--write')) {
  const cell = s => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ');
  const md = `# Quotation register

Generated by \`node tools/quote_register.js --write\`. Do not edit by hand.

${summary}

**What this shows.** Scripture and Qur’an quotations followed by their reference are checked automatically against the text the build script generated for that passage (any translation the reader holds). Hand-entered quotations (creeds, Church Fathers, rabbis, philosophers, modern writers, inscriptions) cannot be checked by script. Unless a source record in \`assets/data/sources.js\` says otherwise, they have not been re-checked against a printed edition in this revision: treat them as attributed quotations to verify. A locator shows where to look, not that the wording is right.

## Hand-entered quotations

| Where | Quotation | Locator follows |
|---|---|---|
${hand.map(r => `| \`${cell(r.where)}\` | “${cell(r.q.length > 160 ? r.q.slice(0, 157) + '…' : r.q)}”${r.cite ? ` (${cell(r.cite)})` : ''} | ${r.locator ? 'yes' : '**no**'} |`).join('\n')}

## Scripture and Qur’an quotations checked against the generated text

| Where | Reference | Result |
|---|---|---|
${scripture.map(r => `| \`${cell(r.where)}\` | ${cell(r.ref)} | ${r.match ? 'matches' : '**not found**'} |`).join('\n')}
`;
  fs.mkdirSync(path.join(__dirname, '..', 'docs'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, '..', 'docs', 'QUOTATIONS.md'), md);
  console.log('wrote docs/QUOTATIONS.md');
}
process.exit(bad ? 1 : 0);
