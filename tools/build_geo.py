"""Build assets/data/geo.js from Natural Earth 1:50m data (public domain).

Usage: python3 tools/build_geo.py <dir containing ne_50m_*.geojson>
Downloads: https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
  ne_50m_land.geojson, ne_50m_lakes.geojson, ne_50m_rivers_lake_centerlines.geojson
The projection constants must match proj() in assets/app/w-history.js.
"""
import json, math, sys, os

LON0, LON1, LAT0, LAT1 = -12.0, 122.0, 0.0, 62.0
K, C = 10.0, math.cos(math.radians(38))
PAD = 3.0  # degrees beyond the frame before clamping, so clamp artefacts stay off-screen

def proj(lon, lat):
    lon = min(max(lon, LON0 - PAD), LON1 + PAD)
    lat = min(max(lat, LAT0 - PAD), LAT1 + PAD)
    return ((lon - LON0) * K * C, (LAT1 - lat) * K)

def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        n = math.hypot(dx, dy) or 1e-9
        best, idx = 0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / n
            if d > best:
                best, idx = d, i
        if best > eps and idx > 0:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]

def area(pts):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(pts, pts[1:] + pts[:1]))) / 2

def in_frame(ring):
    lons = [p[0] for p in ring]; lats = [p[1] for p in ring]
    return not (max(lons) < LON0 - PAD or min(lons) > LON1 + PAD or max(lats) < LAT0 - PAD or min(lats) > LAT1 + PAD)

def fmt(pts, close=True):
    s = 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts)
    return s + ('Z' if close else '')

def polys(feature):
    g = feature['geometry']
    if g['type'] == 'Polygon':
        return [g['coordinates']]
    if g['type'] == 'MultiPolygon':
        return g['coordinates']
    return []

def build_area(path, eps, min_area, keep=lambda f: True):
    out = []
    for f in json.load(open(path))['features']:
        if not keep(f):
            continue
        for poly in polys(f):
            for ring in poly:
                if not in_frame(ring):
                    continue
                pts = [proj(*p) for p in ring]
                mid = len(pts) // 2  # closed ring: simplify each half so the endpoints differ
                pts = rdp(pts[:mid + 1], eps) + rdp(pts[mid:], eps)[1:]
                if len(pts) >= 3 and area(pts) >= min_area:
                    out.append(fmt(pts))
    return ''.join(out)

RIVERS = {'Nile', 'Tigris', 'Euphrates', 'Jordan', 'Tiber', 'Danube', 'Rhine', 'Indus', 'Ganges', 'Rhône', 'Seine', 'Thames', 'Huang', 'Yangtze', 'Orontes'}

def build_rivers(path, eps):
    out = {}
    for f in json.load(open(path))['features']:
        name = f['properties'].get('name') or ''
        key = next((r for r in RIVERS if r.lower() in name.lower()), None)
        if not key:
            continue
        g = f['geometry']
        lines = [g['coordinates']] if g['type'] == 'LineString' else g['coordinates']
        for ln in lines:
            if not in_frame(ln):
                continue
            pts = rdp([proj(*p) for p in ln], eps)
            out.setdefault(key, []).append(fmt(pts, close=False))
    return {k: ''.join(v) for k, v in out.items()}

if __name__ == '__main__':
    src = sys.argv[1]
    land = build_area(os.path.join(src, 'ne_50m_land.geojson'), 0.45, 1.5)
    lakes = build_area(os.path.join(src, 'ne_50m_lakes.geojson'), 0.45, 4,
                       keep=lambda f: (f['properties'].get('scalerank') or 9) <= 3)
    rivers = build_rivers(os.path.join(src, 'ne_50m_rivers_lake_centerlines.geojson'), 0.6)
    W, H = (LON1 - LON0) * K * C, (LAT1 - LAT0) * K
    data = {'w': round(W, 1), 'h': round(H, 1), 'land': land, 'lakes': lakes, 'rivers': rivers}
    dest = os.path.join(os.path.dirname(__file__), '..', 'assets', 'data', 'geo.js')
    with open(dest, 'w') as fh:
        fh.write('/* Generated by tools/build_geo.py from Natural Earth 1:50m (public domain). Do not edit. */\n')
        fh.write('window.GEO = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(dest, os.path.getsize(dest), 'bytes; rivers:', sorted(rivers))
